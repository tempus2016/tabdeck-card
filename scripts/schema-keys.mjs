// Writes src/lib/schema-keys.ts: the top-level and per-tab option names from
// the JSON schema, for the editor's config check (unknown keys). Run after
// changing docs-site/public/schema/tabdeck-card.schema.json:
//   node scripts/schema-keys.mjs
// src/lib/lint.test.ts fails while the file is out of date.
import { readFileSync, writeFileSync } from "node:fs";

const schema = JSON.parse(readFileSync("docs-site/public/schema/tabdeck-card.schema.json", "utf8"));
const top = Object.keys(schema.properties).sort();
const tab = Object.keys(schema.definitions.tab.properties).sort();
const list = (keys) => keys.map((k) => JSON.stringify(k)).join(", ");
writeFileSync(
  "src/lib/schema-keys.ts",
  `// Generated by scripts/schema-keys.mjs from the JSON schema. Don't edit.
export const TOP_KEYS = new Set<string>([${list(top)}]);
export const TAB_KEYS = new Set<string>([${list(tab)}]);
`,
);
console.log(`schema-keys: ${top.length} top-level, ${tab.length} tab keys`);
